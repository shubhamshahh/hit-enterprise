-- 1. PRODUCTS TABLE
CREATE TABLE IF NOT EXISTS public.products (
  id BIGINT PRIMARY KEY,
  name TEXT NOT NULL,
  cas TEXT DEFAULT '',
  grade TEXT DEFAULT '',
  category TEXT DEFAULT '',
  purity TEXT DEFAULT '',
  packaging TEXT DEFAULT '',
  stock_qty TEXT DEFAULT '0',
  stock_unit TEXT DEFAULT 'Bags',
  stock_status TEXT DEFAULT 'optimal',
  applications TEXT DEFAULT '',
  status TEXT DEFAULT 'active',
  image TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

-- Index for speedy catalog queries
CREATE INDEX IF NOT EXISTS idx_products_status ON public.products(status);
CREATE INDEX IF NOT EXISTS idx_products_category ON public.products(category);

-- 2. INQUIRIES & QUOTE REQUESTS TABLE
CREATE TABLE IF NOT EXISTS public.inquiries (
  id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
  name TEXT NOT NULL,
  company TEXT DEFAULT '',
  email TEXT DEFAULT '',
  phone TEXT NOT NULL,
  chemical TEXT NOT NULL,
  quantity TEXT NOT NULL,
  unit TEXT DEFAULT 'kg',
  industry TEXT DEFAULT '',
  message TEXT DEFAULT '',
  status TEXT DEFAULT 'new',
  source TEXT DEFAULT 'form',
  admin_notes TEXT DEFAULT '',
  created_at TIMESTAMPTZ DEFAULT NOW(),
  updated_at TIMESTAMPTZ DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_inquiries_status ON public.inquiries(status);
CREATE INDEX IF NOT EXISTS idx_inquiries_created_at ON public.inquiries(created_at DESC);

-- 3. ROW LEVEL SECURITY (RLS) POLICIES
ALTER TABLE public.products ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;

-- Drop existing policies if re-running script
DROP POLICY IF EXISTS "Public can view active products" ON public.products;
DROP POLICY IF EXISTS "Service role full access on products" ON public.products;
DROP POLICY IF EXISTS "Public can submit inquiries" ON public.inquiries;
DROP POLICY IF EXISTS "Service role full access on inquiries" ON public.inquiries;

-- Anyone can view products (visitors on public site)
CREATE POLICY "Public can view active products" 
  ON public.products FOR SELECT 
  USING (true);

-- Backend (service role / admin) has full CRUD on products
CREATE POLICY "Service role full access on products" 
  ON public.products FOR ALL 
  USING (true) WITH CHECK (true);

-- Anyone can submit a quote request / inquiry
CREATE POLICY "Public can submit inquiries" 
  ON public.inquiries FOR INSERT 
  WITH CHECK (true);

-- Backend (service role / admin) has full CRUD on inquiries
CREATE POLICY "Service role full access on inquiries" 
  ON public.inquiries FOR ALL 
  USING (true) WITH CHECK (true);

-- 4. SUPABASE STORAGE BUCKET FOR PRODUCT IMAGES
-- Creates a public bucket named 'product-images'
INSERT INTO storage.buckets (id, name, public)
VALUES ('product-images', 'product-images', true)
ON CONFLICT (id) DO UPDATE SET public = true;

-- Storage policies: Anyone can view product photos via CDN URL
DROP POLICY IF EXISTS "Public can view product images" ON storage.objects;
CREATE POLICY "Public can view product images" 
  ON storage.objects FOR SELECT 
  USING (bucket_id = 'product-images');

-- Allow backend / service role to upload, update & delete photos
DROP POLICY IF EXISTS "Allow uploads to product-images" ON storage.objects;
CREATE POLICY "Allow uploads to product-images" 
  ON storage.objects FOR INSERT 
  WITH CHECK (bucket_id = 'product-images');

DROP POLICY IF EXISTS "Allow updates to product-images" ON storage.objects;
CREATE POLICY "Allow updates to product-images" 
  ON storage.objects FOR UPDATE 
  USING (bucket_id = 'product-images');

DROP POLICY IF EXISTS "Allow deletes to product-images" ON storage.objects;
CREATE POLICY "Allow deletes to product-images" 
  ON storage.objects FOR DELETE 
  USING (bucket_id = 'product-images');

